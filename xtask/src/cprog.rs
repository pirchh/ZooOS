//! C programs for ZooOS (docs/posix5-design.md): finds the pinned Zig
//! toolchain, generates `zoo_abi.h` from the Rust ABI crate, and builds each
//! program in `c/programs/` as a static freestanding ELF.

use std::path::{Path, PathBuf};
use std::process::Command;
use zoo_abi::sys;

/// The pinned toolchain (tools/zig/README.md).
pub const ZIG_VERSION: &str = "0.16.0";
pub const ZIG_DIR: &str = "zig-x86_64-windows-0.16.0";

/// C programs packed into the initrd as `bin/<name>`.
pub const C_PROGRAMS: [&str; 2] = ["puffin-test", "tern-test"];
/// Ordinary Linux programs (`c/linux/`), built for x86_64-linux-musl and
/// packed as `linux/<name>` (docs/linux1-design.md).
pub const LINUX_PROGRAMS: [&str; 9] = [
    "hello",
    "eider-test",
    "skua-test",
    "fulmar-test",
    "guillemot-test",
    "kittiwake-test",
    "ermine-test",
    "auklet-test",
    "loon-test",
];

/// Linux programs without a C library, linked at a fixed address the way
/// Wine's preloader is (name, image base), packed as `linux/<name>`
/// (docs/linux9-design.md).
pub const LINUX_FREESTANDING: [(&str, &str); 1] = [("redpoll-test", "0x7d7d00000000")];

/// Shared libraries (`c/linux/<name>.c`), packed as `lib/<name>.so`, and
/// dynamically linked programs (output name, source, libraries), packed as
/// `linux/<name>` (docs/linux8-design.md). Both need musl's loader.
pub const LINUX_LIBRARIES: [&str; 2] = ["libdovekie", "libdovekie-plugin"];
pub const LINUX_DYNAMIC: [(&str, &str, &[&str]); 2] = [
    ("hello-dyn", "hello", &[]),
    ("dovekie-test", "dovekie-test", &["-ldovekie"]),
];

/// Where user programs must lie (the kernel's load window).
const IMAGE_START: u64 = 0x20_0000;
const IMAGE_END: u64 = 0x4000_0000;
/// Where Linux programs may lie: 64 KiB up to the 8 MiB stack below
/// 0x7fff_fff1_0000 (docs/linux9-design.md).
const LINUX_IMAGE_START: u64 = 0x1_0000;
const LINUX_IMAGE_END: u64 = 0x7FFF_FFF1_0000 - 8 * 1024 * 1024;

/// The `zig` executable, if the toolchain was downloaded.
pub fn zig(root: &Path) -> Option<PathBuf> {
    let exe = if cfg!(windows) { "zig.exe" } else { "zig" };
    let p = root.join("tools").join("zig").join(ZIG_DIR).join(exe);
    p.is_file().then_some(p)
}

/// `zoo_abi.h`: every system call number and error code, from `zoo_abi`.
fn abi_header() -> String {
    let calls: &[(&str, u64)] = &[
        ("ABI_VERSION", sys::ABI_VERSION),
        ("EXIT", sys::EXIT),
        ("YIELD", sys::YIELD),
        ("LOG", sys::LOG),
        ("CHANNEL_CREATE", sys::CHANNEL_CREATE),
        ("SPAWN", sys::SPAWN),
        ("SEND", sys::SEND),
        ("RECV", sys::RECV),
        ("WAIT", sys::WAIT),
        ("CLOSE", sys::CLOSE),
        ("KILL", sys::KILL),
        ("TICKS", sys::TICKS),
        ("SLEEP", sys::SLEEP),
        ("TRY_RECV", sys::TRY_RECV),
        ("DISPLAY_ACQUIRE", sys::DISPLAY_ACQUIRE),
        ("INPUT_READ", sys::INPUT_READ),
        ("FS_STAT", sys::FS_STAT),
        ("MEM_ALLOC", sys::MEM_ALLOC),
        ("FS_MAP", sys::FS_MAP),
        ("FS_ROOT", sys::FS_ROOT),
        ("DIR_OPEN", sys::DIR_OPEN),
        ("DIR_LIST", sys::DIR_LIST),
        ("DIR_STAT", sys::DIR_STAT),
        ("FILE_READ", sys::FILE_READ),
        ("DIR_CREATE", sys::DIR_CREATE),
        ("DIR_REMOVE", sys::DIR_REMOVE),
        ("SPAWN_WITH", sys::SPAWN_WITH),
        ("THREAD_CREATE", sys::THREAD_CREATE),
        ("THREAD_EXIT", sys::THREAD_EXIT),
        ("FUTEX_WAIT", sys::FUTEX_WAIT),
        ("FUTEX_WAKE", sys::FUTEX_WAKE),
        ("SET_FS_BASE", sys::SET_FS_BASE),
        ("VM_RESERVE", sys::VM_RESERVE),
        ("VM_COMMIT", sys::VM_COMMIT),
        ("VM_PROTECT", sys::VM_PROTECT),
        ("VM_DECOMMIT", sys::VM_DECOMMIT),
        ("VM_RELEASE", sys::VM_RELEASE),
        ("VM_QUERY", sys::VM_QUERY),
        ("SET_EXCEPTION_HANDLER", sys::SET_EXCEPTION_HANDLER),
        ("SET_EXCEPTION_STACK", sys::SET_EXCEPTION_STACK),
        ("EXCEPTION_RETURN", sys::EXCEPTION_RETURN),
        ("FILE_CREATE", sys::FILE_CREATE),
        ("FILE_WRITE", sys::FILE_WRITE),
        ("FILE_TRUNCATE", sys::FILE_TRUNCATE),
        ("FILE_REMOVE", sys::FILE_REMOVE),
        ("RENAME", sys::RENAME),
        ("PROCESS_ID", sys::PROCESS_ID),
        ("LOG_ATTACH", sys::LOG_ATTACH),
        ("LOG_READ", sys::LOG_READ),
        ("SEND_HANDLE", sys::SEND_HANDLE),
        ("RECV_HANDLE", sys::RECV_HANDLE),
        ("WAIT_ANY", sys::WAIT_ANY),
        ("BLOCK_ATTACH", sys::BLOCK_ATTACH),
        ("BLOCK_READ", sys::BLOCK_READ),
        ("BLOCK_WRITE", sys::BLOCK_WRITE),
        ("BLOCK_SIZE", sys::BLOCK_SIZE),
        ("MOUSE_READ", sys::MOUSE_READ),
        ("ARGS_GET", sys::ARGS_GET),
        ("CLOCK", sys::CLOCK),
        ("SHM_CREATE", sys::SHM_CREATE),
        ("SHM_MAP", sys::SHM_MAP),
        ("SHM_UNMAP", sys::SHM_UNMAP),
    ];
    let mut h = String::from(
        "/* Generated by `cargo xtask` from the zoo-abi crate. Do not edit. */\n\
         #ifndef ZOO_ABI_H\n#define ZOO_ABI_H\n\n",
    );
    h.push_str(&format!(
        "#define ZOO_ABI_VERSION {}\n",
        zoo_abi::ABI_VERSION
    ));
    h.push_str(&format!(
        "#define ZOO_NO_HANDLE {:#x}ull\n",
        zoo_abi::NO_HANDLE
    ));
    h.push_str(&format!(
        "#define ZOO_MAX_MESSAGE {}\n",
        zoo_abi::MAX_MESSAGE
    ));
    h.push_str(&format!(
        "#define ZOO_MAX_CMDLINE {}\n\n",
        zoo_abi::MAX_CMDLINE
    ));
    for (name, n) in calls {
        h.push_str(&format!("#define ZOO_SYS_{name} {n}\n"));
    }
    h.push('\n');
    let mut code = 1i64;
    while let Some(e) = zoo_abi::Error::from_return(-code) {
        h.push_str(&format!("#define ZOO_E{} {}\n", e.name(), code));
        code += 1;
    }
    h.push_str("\n#endif\n");
    h
}

/// Builds every C program into `build/c/`; returns (name, bytes).
pub fn build(root: &Path, zig: &Path) -> Result<Vec<(String, Vec<u8>)>, String> {
    let out_dir = root.join("build").join("c");
    std::fs::create_dir_all(&out_dir)
        .map_err(|e| format!("cannot create {}: {e}", out_dir.display()))?;
    std::fs::write(out_dir.join("zoo_abi.h"), abi_header())
        .map_err(|e| format!("cannot write zoo_abi.h: {e}"))?;
    let mut version = Command::new(zig);
    version.arg("version");
    let v =
        crate::process::output_bounded(version, std::time::Duration::from_secs(60), "zig version")?;
    let v = String::from_utf8_lossy(&v.stdout).trim().to_string();
    if v != ZIG_VERSION {
        return Err(format!(
            "tools/zig has zig {v}, but {ZIG_VERSION} is pinned (tools/zig/README.md)"
        ));
    }
    let c = root.join("c");
    let mut built = Vec::new();
    for name in C_PROGRAMS {
        let out = out_dir.join(name);
        let mut cmd = Command::new(zig);
        cmd.current_dir(root)
            .args([
                "cc",
                "-target",
                "x86_64-freestanding-none",
                "-O2",
                "-std=c11",
            ])
            .args(["-Wall", "-Wextra", "-Werror"])
            .args([
                "-ffreestanding",
                "-fno-stack-protector",
                "-fno-pic",
                "-fno-pie",
            ])
            .args(["-nostdlib", "-static"])
            .args(["-Wl,--image-base=0x200000", "-Wl,-e,_start"])
            .arg("-I")
            .arg(c.join("include"))
            .arg("-I")
            .arg(&out_dir)
            .arg("-o")
            .arg(&out)
            .arg(c.join("crt").join("start.c"))
            .arg(c.join("crt").join("string.c"))
            .arg(c.join("programs").join(format!("{name}.c")));
        println!("[build] C program {name} (zig {ZIG_VERSION})");
        let output =
            crate::process::output_bounded(cmd, std::time::Duration::from_secs(300), "zig cc")?;
        if !output.status.success() {
            return Err(format!(
                "zig cc failed for {name}:\n{}",
                String::from_utf8_lossy(&output.stderr)
            ));
        }
        let data =
            std::fs::read(&out).map_err(|e| format!("cannot read {}: {e}", out.display()))?;
        // The kernel's own ELF checks must accept it.
        zoo_abi::elf::parse(&data, IMAGE_START, IMAGE_END)
            .map_err(|e| format!("{name}: the kernel would reject this ELF: {e:?}"))?;
        built.push((format!("bin/{name}"), data));
    }
    // Linux programs: nothing ZooOS-specific, the standard musl target.
    for name in LINUX_PROGRAMS {
        let out = out_dir.join(format!("linux-{name}"));
        let mut cmd = Command::new(zig);
        cmd.current_dir(root)
            .args(["cc", "-target", "x86_64-linux-musl", "-O2", "-std=c11"])
            .args(["-Wall", "-Wextra", "-Werror"])
            .args(["-static", "-fno-pie", "-no-pie", "-s"])
            .arg("-o")
            .arg(&out)
            .arg(c.join("linux").join(format!("{name}.c")));
        println!("[build] Linux program {name} (zig {ZIG_VERSION}, x86_64-linux-musl)");
        let output =
            crate::process::output_bounded(cmd, std::time::Duration::from_secs(300), "zig cc")?;
        if !output.status.success() {
            return Err(format!(
                "zig cc failed for linux/{name}:\n{}",
                String::from_utf8_lossy(&output.stderr)
            ));
        }
        let data =
            std::fs::read(&out).map_err(|e| format!("cannot read {}: {e}", out.display()))?;
        zoo_abi::elf::parse(&data, LINUX_IMAGE_START, LINUX_IMAGE_END)
            .map_err(|e| format!("linux/{name}: the kernel would reject this ELF: {e:?}"))?;
        built.push((format!("linux/{name}"), data));
    }
    for (name, base) in LINUX_FREESTANDING {
        let out = out_dir.join(format!("linux-{name}"));
        let mut cmd = Command::new(zig);
        cmd.current_dir(root)
            .args(["cc", "-target", "x86_64-linux-musl", "-O2", "-std=c11"])
            .args(["-Wall", "-Wextra", "-Werror", "-nostdlib", "-ffreestanding"])
            // Full 64-bit addresses: the image lies far above 4 GiB.
            .args([
                "-fno-stack-protector",
                "-mcmodel=large",
                "-fno-pie",
                "-no-pie",
            ])
            .args(["-static", "-s"])
            .arg(format!("-Wl,--image-base={base}"))
            .arg("-o")
            .arg(&out)
            .arg(c.join("linux").join(format!("{name}.c")));
        println!("[build] Linux program {name} (zig {ZIG_VERSION}, freestanding at {base})");
        let output =
            crate::process::output_bounded(cmd, std::time::Duration::from_secs(300), "zig cc")?;
        if !output.status.success() {
            return Err(format!(
                "zig cc failed for linux/{name}:\n{}",
                String::from_utf8_lossy(&output.stderr)
            ));
        }
        let data =
            std::fs::read(&out).map_err(|e| format!("cannot read {}: {e}", out.display()))?;
        zoo_abi::elf::parse(&data, LINUX_IMAGE_START, LINUX_IMAGE_END)
            .map_err(|e| format!("linux/{name}: the kernel would reject this ELF: {e:?}"))?;
        built.push((format!("linux/{name}"), data));
    }
    // musl's dynamic loader, shared libraries and dynamically linked
    // programs (docs/linux8-design.md).
    match crate::musl::source(root) {
        Some(src) => {
            let complex_mul = root.join("c").join("musl").join("complex-mul.c");
            let so = crate::musl::build_libc_so(zig, &src, &complex_mul, &root.join("build"))?;
            built.push(("lib/ld-musl-x86_64.so.1".to_string(), so));
            let run = |cmd: Command, what: &str| -> Result<(), String> {
                let o = crate::process::output_bounded(
                    cmd,
                    std::time::Duration::from_secs(300),
                    "zig cc",
                )?;
                if o.status.success() {
                    Ok(())
                } else {
                    Err(format!(
                        "zig cc failed for {what}:\n{}",
                        String::from_utf8_lossy(&o.stderr)
                    ))
                }
            };
            for name in LINUX_LIBRARIES {
                let out = out_dir.join(format!("{name}.so"));
                let mut cmd = Command::new(zig);
                cmd.current_dir(root)
                    .args(["cc", "-target", "x86_64-linux-musl", "-O2", "-std=c11"])
                    .args(["-Wall", "-Wextra", "-Werror", "-shared", "-fPIC", "-s"])
                    // Programs then record the library by this name, not by
                    // its path on the build machine.
                    .arg(format!("-Wl,-soname,{name}.so"))
                    .arg("-o")
                    .arg(&out)
                    .arg(c.join("linux").join(format!("{name}.c")));
                println!("[build] Linux library {name}.so (zig {ZIG_VERSION}, x86_64-linux-musl)");
                run(cmd, &format!("lib/{name}.so"))?;
                let data = std::fs::read(&out)
                    .map_err(|e| format!("cannot read {}: {e}", out.display()))?;
                built.push((format!("lib/{name}.so"), data));
            }
            for (name, source, libs) in LINUX_DYNAMIC {
                let out = out_dir.join(format!("linux-{name}"));
                let mut cmd = Command::new(zig);
                cmd.current_dir(root)
                    .args(["cc", "-target", "x86_64-linux-musl", "-O2", "-std=c11"])
                    .args([
                        "-Wall", "-Wextra", "-Werror", "-dynamic", "-fno-pie", "-no-pie", "-s",
                    ])
                    .arg("-o")
                    .arg(&out)
                    .arg(c.join("linux").join(format!("{source}.c")))
                    .arg(format!("-L{}", out_dir.display()))
                    .args(libs.iter());
                println!(
                    "[build] Linux program {name} (zig {ZIG_VERSION}, x86_64-linux-musl, dynamic)"
                );
                run(cmd, &format!("linux/{name}"))?;
                let data = std::fs::read(&out)
                    .map_err(|e| format!("cannot read {}: {e}", out.display()))?;
                zoo_abi::elf::parse(&data, LINUX_IMAGE_START, LINUX_IMAGE_END).map_err(|e| {
                    format!("linux/{name}: the kernel would reject this ELF: {e:?}")
                })?;
                built.push((format!("linux/{name}"), data));
            }
        }
        None => println!(
            "[build] no musl {} source in tools/musl (tools/musl/README.md): no dynamic loader",
            crate::musl::MUSL_VERSION
        ),
    }
    Ok(built)
}
